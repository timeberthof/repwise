import { test, expect } from '@playwright/test'
import { seededApp, shot } from './helpers'

test('Wöchentlicher Check-in: Gewicht Pflicht, Foto „Später“', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-21T19:00:00'))
  await seededApp(page, '/home', { checkin: false })
  const sheet = page.getByRole('dialog', { name: 'Wöchentlicher Check-in' })
  await expect(sheet).toBeVisible()
  await expect(sheet.getByRole('button', { name: 'Weiter' })).toBeDisabled()
  await page.screenshot({ path: shot('E-checkin-gewicht') })
  await sheet.getByLabel('Körpergewicht in kg').fill('86,4')
  await sheet.getByRole('button', { name: 'Weiter' }).click()
  await expect(sheet.getByText('Fortschrittsfoto')).toBeVisible()
  await page.screenshot({ path: shot('E-checkin-foto') })
  await sheet.getByRole('button', { name: 'Später' }).click()
  await expect(sheet).toBeHidden()
  // Hinweis auf dem Dashboard, Gewicht ist gespeichert
  await expect(page.getByText('Fortschrittsfoto fehlt')).toBeVisible()
  await page.goto('/?sim=iphone#/koerper')
  await page.reload()
  await page.waitForTimeout(1200)
  // beim nächsten Start: nur die Foto-Abfrage
  await expect(page.getByRole('dialog', { name: 'Wöchentlicher Check-in' }).getByText('Fortschrittsfoto')).toBeVisible()
  await page.getByRole('button', { name: 'Später' }).click()
  await page.waitForTimeout(500)
  await expect(page.getByText('86,4 kg').first()).toBeVisible()
  await page.screenshot({ path: shot('E-koerper') })
})

test('Training selbst erfassen: Vorlage, Sätze, Abschluss, Verlauf', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-21T19:00:00'))
  page.on('console', (m) => m.type() === 'error' && console.log('[browser]', m.text()))
  await seededApp(page, '/vorlagen/neu')
  await page.getByLabel('Name der Vorlage').fill('Push')
  await page.getByRole('button', { name: 'Übungen hinzufügen' }).click()
  const picker = page.getByRole('dialog', { name: 'Übungen wählen' })
  await picker.getByRole('button', { name: /Bankdrücken an der Multipresse/ }).click()
  await picker.getByRole('button', { name: /^Butterfly$/ }).click()
  await picker.getByRole('button', { name: '2 hinzufügen' }).click()
  await page.waitForTimeout(400)
  await page.screenshot({ path: shot('E-vorlage') })
  await page.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(page).toHaveURL(/#\/vorlagen$/)
  await expect(page.getByText('Push', { exact: true })).toBeVisible()

  await page.goto('/?sim=iphone#/training')
  await page.reload()
  await page.waitForTimeout(1200)
  await page.screenshot({ path: shot('E-training') })
  await page.getByRole('button', { name: /^Push/ }).click()
  await expect(page).toHaveURL(/#\/workout\/\d+$/)
  await page.waitForTimeout(800)

  const bank = page.getByRole('region', { name: 'Bankdrücken an der Multipresse' })
  await expect(bank.getByText('Letztes Mal')).toBeVisible()
  // keine vorausgefüllten Werte
  await expect(bank.getByLabel('Neuer Satz Gewicht')).toHaveValue('')
  await expect(bank.getByLabel('Neuer Satz Wiederholungen')).toHaveValue('')
  await bank.getByLabel('Neuer Satz Gewicht').fill('52,5')
  await bank.getByLabel('Neuer Satz Wiederholungen').fill('8')
  await bank.getByRole('button', { name: 'Satz eintragen' }).click()
  await bank.getByRole('button', { name: 'Wie Satz 1' }).click()
  await bank.getByLabel('Satz 2 Wiederholungen').fill('7')
  await bank.getByLabel('Satz 2 RIR').fill('1')
  await bank.getByLabel('Satz 2 RIR').blur()
  await page.waitForTimeout(400)
  await expect(page.getByRole('timer')).toBeVisible()
  await page.screenshot({ path: shot('E-workout') })

  // Butterfly ohne Satz → wird beim Beenden entfernt
  await page.getByRole('button', { name: 'Training beenden' }).click()
  await expect(page).toHaveURL(/abschluss/)
  await page.waitForTimeout(1200)
  await expect(page.getByText('2', { exact: true }).first()).toBeVisible()
  await page.screenshot({ path: shot('E-abschluss') })

  await page.goto('/?sim=iphone#/verlauf')
  await page.waitForTimeout(1000)
  await page.getByRole('button', { name: /Push/ }).first().click()
  await page.waitForTimeout(800)
  await expect(page.getByText('7 Wdh')).toBeVisible()
  await expect(page.getByText('Butterfly', { exact: true })).toHaveCount(0)
  await page.screenshot({ path: shot('E-verlauf-detail') })
})
